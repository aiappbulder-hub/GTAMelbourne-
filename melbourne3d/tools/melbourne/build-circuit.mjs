// tools/melbourne/build-circuit.mjs: the Albert Park Grand Prix circuit as one closed loop, from OSM's
// "Albert Park Circuit" relation (its forward ways: Aughtie Drive, Albert Road Drive, Lakeside Drive, Ross Gregory
// Drive and the raceway-only links between them; not the pit lane), chained end to end, resampled every 4 m and
// written to js/albert-park-circuit.js, starting on the start/finish line and running the race direction (clockwise).
import fs from 'node:fs';
import { loadOSM, wayPts, log } from './osm.mjs';

const { nodes, ways, relations } = loadOSM();
const rel = [...relations.values()].find((r) => r.tags && r.tags.name === 'Albert Park Circuit');
if (!rel) throw new Error('no Albert Park Circuit relation in the OSM tiles');
let segs = rel.members.filter((m) => m.type === 'way' && m.role !== 'pit_lane' && ways.has(m.ref))
  .map((m) => wayPts(ways.get(m.ref), nodes));
const pit = rel.members.find((m) => m.role === 'pit_lane');
const same = (a, b) => Math.hypot(a[0] - b[0], a[1] - b[1]) < 0.5;
// chain: start with the first, keep appending whichever segment touches the end (reversed if need be)
const loop = [...segs.shift()];
while (segs.length) {
  const end = loop[loop.length - 1];
  let k = segs.findIndex((s) => same(s[0], end));
  let s;
  if (k >= 0) s = segs[k];
  else {
    k = segs.findIndex((s) => same(s[s.length - 1], end));
    if (k < 0) throw new Error(`the circuit breaks at ${end}`);
    s = [...segs[k]].reverse();
  }
  segs.splice(k, 1);
  loop.push(...s.slice(1));
}
if (!same(loop[0], loop[loop.length - 1])) throw new Error('the circuit does not close');
loop.pop();
// the relation's first member is a forward way, so the chain already runs the race direction (clockwise)
// the start/finish line: halfway along the pit straight (beside the pit lane)
const pitPts = pit && ways.has(pit.ref) ? wayPts(ways.get(pit.ref), nodes) : null;
let start = 0;
if (pitPts) {
  const mid = pitPts[pitPts.length >> 1];
  let bd = Infinity;
  loop.forEach((p, i) => { const d = Math.hypot(p[0] - mid[0], p[1] - mid[1]); if (d < bd) { bd = d; start = i; } });
}
const ordered = [...loop.slice(start), ...loop.slice(0, start)];
// resample every 4 m
const out = [];
let carry = 0;
for (let i = 0; i < ordered.length; i++) {
  const a = ordered[i], b = ordered[(i + 1) % ordered.length];
  const L = Math.hypot(b[0] - a[0], b[1] - a[1]);
  for (let s = carry; s < L; s += 4) out.push(a[0] + ((b[0] - a[0]) * s) / L, a[1] + ((b[1] - a[1]) * s) / L);
  carry = (carry - L) % 4;
  if (carry < 0) carry += 4;
}
let length = 0;
for (let i = 0; i < out.length; i += 2) {
  const j = (i + 2) % out.length;
  length += Math.hypot(out[j] - out[i], out[j + 1] - out[i + 1]);
}
const flat = out.map((v) => Math.round(v * 10) / 10);
const pitFlat = pitPts ? pitPts.flat().map((v) => Math.round(v * 10) / 10) : [];
const file = new URL('../../js/albert-park-circuit.js', import.meta.url);
fs.writeFileSync(file, `// The Albert Park Grand Prix circuit: a closed loop of x, z points every 4 m (world frame), from the start/finish line
// in the race direction (clockwise), and the pit lane. Generated by tools/melbourne/build-circuit.mjs from OSM
// (© OpenStreetMap contributors, ODbL). Do not edit.
export const CIRCUIT_LENGTH = ${Math.round(length)};
export const CIRCUIT = new Float32Array(${JSON.stringify(flat)});
export const PIT_LANE = new Float32Array(${JSON.stringify(pitFlat)});
`);
log(`Albert Park circuit: ${flat.length / 2} points, ${(length / 1000).toFixed(2)} km, start at ${flat[0]}, ${flat[1]}`);
