// tools/melbourne/patch-cuttings.mjs: the kerb islands and parks over a freeway's road where it runs at or near the
// ground (its open cuttings, including the one js/freeway-data.js adds for the Burnley Tunnel's exit, and its at-grade
// and low stretches, which the refine pass's block patches, js/melbourne-freeways.js blockPatches, never cut: there the
// islands' 0.22 m slabs and the parks' lawns buried the road), cut round them as refine-freeways.mjs does: the block's
// outline on a 1 m raster, the cuttings' outlines and the low roads (0.3 m past each edge) taken out, the pieces traced
// and simplified, any cutting wholly inside a piece kept as its hole.
//   node tools/melbourne/patch-cuttings.mjs   -> writes js/freeway-block-patches.js
// Run it again whenever js/freeway-data.js changes a cutting.
import fs from 'node:fs';
import { Raster, rdpRing } from '../geo-geometry.mjs';
import { makeBlocks } from './blocks.mjs';

const JS = new URL('../../js/', import.meta.url);
const { GEO } = await import(new URL('melbourne-geodata.js', JS));
const { RAW_PATCHES, FREEWAYS } = await import(new URL('freeway-data.js', JS));
const q = (v) => Math.round(v * 10) / 10;
const flatRing = (r) => r.flatMap(([x, z]) => [q(x), q(z)]);
const toRing = (t) => { const r = []; for (let i = 0; i < t.length; i += 2) r.push([t[i], t[i + 1]]); return r; };
const pip = (x, z, r) => { let ins = false; for (let i = 0, j = r.length - 1; i < r.length; j = i++) { const [xa, za] = r[i], [xb, zb] = r[j]; if ((za > z) !== (zb > z) && x < ((xb - xa) * (z - za)) / (zb - za) + xa) ins = !ins; } return ins; };
const rings = FREEWAYS.trenches.map(toRing);
// the low roads: every open segment less than 0.8 m over the ground at both ends, as a quad 0.3 m past each edge
for (const [, , width, , f] of FREEWAYS.ways) {
  const o = width / 2 + 0.3;
  for (let i = 0; i + 1 < f.length / 4; i++) {
    if ((f[i * 4 + 3] === 1 && f[i * 4 + 7] === 1) || Math.max(f[i * 4 + 2], f[i * 4 + 6]) >= 0.8) continue;
    const ax = f[i * 4], az = f[i * 4 + 1], bx = f[i * 4 + 4], bz = f[i * 4 + 5], L = Math.hypot(bx - ax, bz - az);
    if (L < 0.1) continue;
    const ux = (bx - ax) / L, uz = (bz - az) / L, nx = -uz * o, nz = ux * o, e = 1; // (1 m past each end: no seams)
    rings.push([[ax + nx - ux * e, az + nz - uz * e], [bx + nx + ux * e, bz + nz + uz * e], [bx - nx + ux * e, bz - nz + uz * e], [ax - nx - ux * e, az - nz - uz * e]]);
  }
}
const rb = rings.map((r) => [Math.min(...r.map((p) => p[0])), Math.max(...r.map((p) => p[0])), Math.min(...r.map((p) => p[1])), Math.max(...r.map((p) => p[1]))]);
const out = {};
GEO.blocks.forEach(([flat, , , , isRect], id) => {
  if (isRect) return;
  const poly = toRing(flat);
  const x0 = Math.min(...poly.map((p) => p[0])), x1 = Math.max(...poly.map((p) => p[0])), z0 = Math.min(...poly.map((p) => p[1])), z1 = Math.max(...poly.map((p) => p[1]));
  const hits = rings.filter((r, k) => rb[k][0] < x1 && rb[k][1] > x0 && rb[k][2] < z1 && rb[k][3] > z0);
  if (!hits.length) return;
  // the area still over a cutting: of the refine pass's patch if it has one, else of the whole block
  const over = (pieces) => {
    const R = new Raster(x0 - 4, z0 - 4, x1 + 4, z1 + 4, 1);
    for (const r of pieces) R.fillRing(r, 1);
    let a = 0; for (const v of R.d) a += v;
    for (const r of hits) R.fillRing(r, 0);
    let b = 0; for (const v of R.d) b += v;
    return a - b;
  };
  const raw = RAW_PATCHES[id];
  if (over(raw ? raw.map(([outer]) => toRing(outer)) : [poly]) < 20) return;
  const R = new Raster(x0 - 4, z0 - 4, x1 + 4, z1 + 4, 1);
  R.fillRing(poly, 1);
  for (const r of hits) R.fillRing(r, 0);
  const pieces = makeBlocks({ land: R, roads: [], sidewalk: 1, log: () => {} }).filter((b) => b.area > 25);
  // a piece's holes: the cut-away regions wholly inside its outline (a cutting or a low road running inside a park),
  // traced from the raster as single merged outlines, so no two holes overlap
  out[id] = pieces.map((b) => {
    const outer = rdpRing(b.poly, 0.4);
    const H = new Raster(x0 - 4, z0 - 4, x1 + 4, z1 + 4, 1);
    H.fillRing(outer, 1);
    for (let k = 0; k < H.d.length; k++) if (R.d[k]) H.d[k] = 0;
    const holes = makeBlocks({ land: H, roads: [], sidewalk: 1, log: () => {} }).filter((h) => h.area > 8)
      .map((h) => rdpRing(h.poly, 0.4)).filter((h) => h.every(([x, z]) => pip(x, z, outer)));
    return [outer, ...holes].map(flatRing);
  });
  console.log(`block ${id}: ${pieces.length} pieces`);
});
const head = '// js/freeway-block-patches.js: GENERATED by tools/melbourne/patch-cuttings.mjs, do not edit by hand. Kerb islands and parks\n' +
  '// cut round the freeways\' open cuttings and low roads (js/city-grid.js blockPatches: block id -> [outer, ...holes]).\n';
fs.writeFileSync(new URL('freeway-block-patches.js', JS), head + 'export const BLOCK_PATCHES = ' + JSON.stringify(out) + ';\n');
console.log('blocks patched:', Object.keys(out).join(', ') || 'none');
