// tools/melbourne/build-trees.mjs: writes js/melbourne-tree-geodata.js and its .bin.gz asset, Melbourne's mapped
// trees in the engine's NYT1 format (the layout tools/build-trees.py writes for New York, so the loader is the same).
//
// usage: node tools/melbourne/build-trees.mjs   (after tools/melbourne/fetch-osm.mjs)
//
// Source: OpenStreetMap natural=tree nodes (much of the City of Melbourne's urban forest is mapped tree by tree).
// Positions are quantised to 0.5 m, duplicates dropped, and the points put in Morton order for compression.
// Data © OpenStreetMap contributors (ODbL).
import fs from 'node:fs';
import zlib from 'node:zlib';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { loadOSM, toWorld, log } from './osm.mjs';

const OUT_JS = fileURLToPath(new URL('../../js/melbourne-tree-geodata.js', import.meta.url));
const OUT_BIN = OUT_JS.replace(/\.js$/, '.bin.gz');

const { taggedNodes } = loadOSM();
const seen = new Set();
const pts = [];
for (const n of taggedNodes.values()) {
  if (n.tags.natural !== 'tree') continue;
  const [x, z] = toWorld(n.lon, n.lat);
  const p = [Math.round(x * 2), Math.round(z * 2)];
  const k = `${p[0]},${p[1]}`;
  if (seen.has(k)) continue;
  seen.add(k);
  pts.push(p);
}
const morton = ([x, z]) => {
  x += 16384; z += 16384;
  let o = 0;
  for (let i = 0; i < 16; i++) o += ((x >> i) & 1) * 2 ** (2 * i) + ((z >> i) & 1) * 2 ** (2 * i + 1);
  return o;
};
pts.sort((a, b) => morton(a) - morton(b));

const xs = [], zs = [];
const sint = (arr, v) => { v = v >= 0 ? v * 2 : -v * 2 - 1; while (v > 127) { arr.push((v & 127) | 128); v >>>= 7; } arr.push(v); };
let px = 0, pz = 0;
for (const [x, z] of pts) { sint(xs, x - px); sint(zs, z - pz); px = x; pz = z; }
const header = Buffer.alloc(12);
header.write('NYT1', 0, 'latin1');
header.writeUInt32LE(pts.length, 4);
header.writeUInt32LE(xs.length, 8);
const raw = Buffer.concat([header, Buffer.from(xs), Buffer.from(zs)]);
const gz = zlib.gzipSync(raw, { level: 9 });
gz.writeUInt32LE(0, 4);
fs.writeFileSync(OUT_BIN, gz);

const nyc = fs.readFileSync(fileURLToPath(new URL('../../js/tree-geodata.js', import.meta.url)), 'utf8');
const body = nyc.slice(nyc.indexOf('const response'));
fs.writeFileSync(OUT_JS, `// Generated by tools/melbourne/build-trees.mjs; do not edit.
// Melbourne's mapped trees from OpenStreetMap (© OpenStreetMap contributors, ODbL).
// Data SHA-256: ${crypto.createHash('sha256').update(raw).digest('hex')}
// ${pts.length.toLocaleString('en')} tree locations, quantized to 0.5 m.
${body.replace('./tree-geodata.bin.gz', './melbourne-tree-geodata.bin.gz')}`);
log(`wrote ${pts.length} trees: ${(gz.length / 1024).toFixed(0)} KB gzip`);
