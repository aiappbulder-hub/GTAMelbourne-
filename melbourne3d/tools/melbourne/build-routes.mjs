// tools/melbourne/build-routes.mjs: the routes the story's lead vehicles drive (the hatch that shoots up Sunday lunch,
// the ute from the market to the yards), found along the real street centrelines and written to js/story/routes.js.
// Each route is the shortest way through the listed places, on surface streets (no freeways).
// Run: node tools/melbourne/build-routes.mjs
import fs from 'node:fs';
import { ROADS } from '../../js/melbourne-config.js';

// name → the points it passes through, in order (world metres)
const WANT = {
  // Sunday Lunch: from Lygon St by Argyle Square, by Pelham St and Cardigan St , stopping where it meets Grattan St
  LUNCH_CHASE: [[466, -1317], [446, -1595]],
  // Market Day: Queen Victoria Market, west along Victoria St and down through North Melbourne to the yards at Dudley St and Wurundjeri Way
  MARKET_UTE: [[-345, -1212], [-540, -1312], [-1653, -978]]
};

const SNAP = 4; // metres: points this close are one junction
const nodes = [], cell = new Map();
function node(x, z) {
  const cx = Math.floor(x / SNAP), cz = Math.floor(z / SNAP);
  for (let i = -1; i <= 1; i++) for (let j = -1; j <= 1; j++) {
    for (const k of cell.get(`${cx + i},${cz + j}`) || []) if (Math.hypot(nodes[k].x - x, nodes[k].z - z) < SNAP) return k;
  }
  const k = nodes.push({ x, z, out: [] }) - 1;
  const key = `${cx},${cz}`;
  if (!cell.has(key)) cell.set(key, []);
  cell.get(key).push(k);
  return k;
}
for (const r of ROADS) {
  if (r.highway) continue;
  let prev = -1;
  // (streets that cross needn't share a point: each is walked in 3 m steps, so crossings land within a snap)
  const fine = [];
  r.pts.forEach((p, i) => {
    if (i) {
      const a = r.pts[i - 1], n = Math.ceil(Math.hypot(p.x - a.x, p.z - a.z) / 3);
      for (let j = 1; j < n; j++) fine.push({ x: a.x + ((p.x - a.x) * j) / n, z: a.z + ((p.z - a.z) * j) / n });
    }
    fine.push(p);
  });
  for (const p of fine) {
    const k = node(p.x, p.z);
    if (prev >= 0 && prev !== k) {
      const d = Math.hypot(nodes[k].x - nodes[prev].x, nodes[k].z - nodes[prev].z);
      nodes[prev].out.push([k, d]);
      nodes[k].out.push([prev, d]);
    }
    prev = k;
  }
}
const nearest = ([x, z]) => {
  let best = -1, bd = Infinity;
  nodes.forEach((n, k) => { const d = Math.hypot(n.x - x, n.z - z); if (d < bd && n.out.length) { bd = d; best = k; } });
  return best;
};
function path(a, b) {
  const dist = new Float64Array(nodes.length).fill(Infinity), from = new Int32Array(nodes.length).fill(-1), done = new Uint8Array(nodes.length);
  dist[a] = 0;
  // nearest first: buckets by whole metres
  const buckets = [[a]];
  for (let d = 0; d < buckets.length; d++) for (let q = 0; buckets[d] && q < buckets[d].length; q++) {
    const k = buckets[d][q];
    if (done[k] || dist[k] < d) continue;
    done[k] = 1;
    for (const [n, w] of nodes[k].out) if (dist[k] + w < dist[n]) { dist[n] = dist[k] + w; from[n] = k; (buckets[Math.floor(dist[n])] ||= []).push(n); }
  }
  if (!done[b]) throw new Error('no way through');
  const out = [];
  for (let k = b; k >= 0; k = from[k]) out.unshift(k);
  return out;
}
// drop the points that sit on a straight line between their neighbours (within 1.2 m)
function simplify(pts) {
  const keep = [pts[0]];
  for (let i = 1; i < pts.length - 1; i++) {
    const a = keep[keep.length - 1], b = pts[i + 1], p = pts[i];
    const L = Math.hypot(b.x - a.x, b.z - a.z) || 1;
    if (Math.abs((b.x - a.x) * (p.z - a.z) - (b.z - a.z) * (p.x - a.x)) / L > 1.2) keep.push(p);
  }
  keep.push(pts[pts.length - 1]);
  return keep;
}
const ROUTES = {};
for (const [name, via] of Object.entries(WANT)) {
  const ks = via.map(nearest);
  let all = [ks[0]];
  for (let i = 0; i + 1 < ks.length; i++) all = all.concat(path(ks[i], ks[i + 1]).slice(1));
  const pts = simplify(all.map((k) => nodes[k]));
  let L = 0;
  for (let i = 1; i < pts.length; i++) L += Math.hypot(pts[i].x - pts[i - 1].x, pts[i].z - pts[i - 1].z);
  ROUTES[name] = pts.map((p) => [Math.round(p.x), Math.round(p.z)]);
  console.log(`${name}: ${pts.length} points, ${Math.round(L)} m`);
}
const src = `// js/story/routes.js: the routes the story's lead vehicles drive, along the real street centrelines ([x, z] in world
// metres). Generated by tools/melbourne/build-routes.mjs; edit the places there and run it again.
export const ROUTES = ${JSON.stringify(ROUTES)};
`;
fs.writeFileSync(new URL('../../js/story/routes.js', import.meta.url), src);
